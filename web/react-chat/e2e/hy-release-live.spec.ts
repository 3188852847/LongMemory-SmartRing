import {test,expect} from '@playwright/test';

test('最终组合真实HTTP与SDK：来源、纠正、重读、历史及单条删除',async({page},info)=>{
  const errors:string[]=[];
  const responses:Array<{path:string;status:number}>=[];
  const external:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(new URL(r.url()).origin!==process.env.Z_HY_LIVE_URL)external.push(r.url());});
  page.on('response',r=>{const url=new URL(r.url());if(url.pathname.startsWith('/api/'))responses.push({path:url.pathname,status:r.status()});});
  // No route()/fulfill(): every API response comes from the actual isolated Runtime/SDK.
  await page.setViewportSize({width:1366,height:768});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/memories');
  await expect(page.getByRole('heading',{name:'我的记忆',exact:true})).toBeVisible();
  await expect(page.getByText('合成用户喜欢无糖乌龙茶',{exact:true})).toBeVisible();
  await page.screenshot({path:info.outputPath('z-live-wide.png'),animations:'disabled',fullPage:true});
  await page.getByRole('button',{name:'查看详情'}).first().click();
  const drawer=page.getByRole('dialog',{name:'记忆详情'});
  await expect(drawer).toBeVisible();
  await drawer.getByRole('combobox',{name:'选择一条来源回看'}).selectOption('z-browser-seed');
  await expect(drawer.getByText('用户原话',{exact:true})).toBeVisible();
  await expect(drawer.getByText('合成用户喜欢无糖乌龙茶',{exact:true})).toHaveCount(2);
  await drawer.getByRole('button',{name:'读取这条变化记录'}).click();
  await expect(drawer.getByText('未读到变化记录。可能尚无变化，也可能引擎未开启历史记录。')).toBeVisible();
  const correction=drawer.getByRole('button',{name:'纠正这条记忆'});
  await correction.focus();await page.keyboard.press('Enter');
  const modal=page.getByRole('dialog',{name:'纠正这条记忆'});
  await modal.getByLabel('正确的内容').fill('合成用户现在喜欢无糖茉莉花茶');
  await modal.getByRole('checkbox').check();
  await modal.getByRole('button',{name:'保存纠正',exact:true}).click();
  await expect(modal).toBeHidden();
  await expect(drawer.getByText('合成用户现在喜欢无糖茉莉花茶',{exact:true})).toBeVisible();
  await drawer.getByText(/查看管理纠正的明确指令来源/).click();
  await drawer.getByRole('button',{name:/回看纠正指令/}).click();
  await expect(drawer.getByText('合成用户现在喜欢无糖茉莉花茶',{exact:true})).toHaveCount(2);
  await page.screenshot({path:info.outputPath('z-live-correction-source.png'),animations:'disabled'});
  await page.reload();
  await expect(page.getByRole('dialog',{name:'记忆详情'}).getByText('合成用户现在喜欢无糖茉莉花茶',{exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>document.documentElement.dataset.reading='larger');
  await expect(page.getByText('合成用户现在喜欢无糖茉莉花茶',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:info.outputPath('z-live-narrow-large.png'),animations:'disabled',fullPage:true});
  await page.getByRole('button',{name:'基本画像',exact:true}).click();
  await expect(page.getByText('尚未形成基本画像',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'记录与变化',exact:true}).click();
  await expect(page.getByText('已完成',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'核对条目'}).click();
  await page.getByRole('button',{name:'删除这条记忆',exact:true}).click();
  const removal=page.getByRole('dialog',{name:'删除这条引擎记忆'});
  await removal.getByRole('checkbox').check();
  await removal.getByRole('button',{name:'确认删除条目',exact:true}).click();
  await expect(removal).toBeHidden();
  await page.getByRole('button',{name:'记忆条目',exact:true}).click();
  await expect(page.getByText('这一页还没有记忆条目',{exact:true})).toBeVisible();
  expect(errors).toEqual([]);expect(external).toEqual([]);
  expect(responses.filter(r=>r.status>=400)).toEqual([]);
  await info.attach('actual-api-responses',{body:JSON.stringify(responses,null,2),contentType:'application/json'});
});
